#!/usr/bin/env bash
# Synthesize text as a background job, poll it and check the audio. Usage: 04_tts.sh ["text"]
# Optional: TTS_VOICE_ID, TTS_LANGUAGE (default en), TTS_FORMAT (wav, mp3, flac or ogg).
set -euo pipefail
source "$(dirname "$0")/lib/mcp.sh"
require_tools

text="${1:-Hello from the Voice MCP Server. This sentence was generated by a test script.}"
voice_id="${TTS_VOICE_ID:-$(state_get voice_id)}"
[[ -n "$voice_id" ]] || die "no voice saved: run scripts/02_add_voice.sh first, or set TTS_VOICE_ID"

arguments=$(jq -cn --arg text "$text" --arg voice "$voice_id" --arg language "${TTS_LANGUAGE:-en}" \
  --arg format "${TTS_FORMAT:-}" '{text: $text, voice_id: $voice, language: $language, wait: false}
  + (if $format != "" then {options: {output_format: $format}} else {} end)')

mcp_connect
voices=$(mcp_tool list_voices) || die "list_voices failed: $voices"
voice_name=$(jq -r --arg id "$voice_id" '.voices[] | select(.voice_id == $id) | .name' <<<"$voices")
[[ -n "$voice_name" ]] || die "voice $voice_id does not exist: run scripts/02_add_voice.sh"
submission=$(mcp_tool text_to_speech "$arguments") || die "text_to_speech was rejected: $submission"
pass "submitted text_to_speech with voice $voice_name ($voice_id)"

view=$(mcp_poll_job "$(job_id_of "$submission")") || die "synthesis did not complete"
log "output files:"
check_output_files "$view" >/dev/null
audio=$(jq -r '[.files // {} | .. | strings | select(test("\\.(wav|mp3|flac|ogg)$"))][0] // empty' <<<"$view")
audio="${audio#file://}"
[[ -n "$audio" ]] || die "the job reported no audio file: $view"
if [[ "$audio" == /* ]]; then
  duration=$(ffprobe -v error -show_entries format=duration -of csv=p=0 "$audio")
  awk -v duration="$duration" 'BEGIN {exit !(duration > 0)}' || die "$audio has no audio: duration $duration"
  pass "synthesis completed with ${duration}s of audio: $(display_path "$audio")"
else
  pass "synthesis completed: $audio"
fi
